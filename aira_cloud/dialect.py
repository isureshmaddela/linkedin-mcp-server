"""SQLite-to-PostgreSQL translation for the control plane.

The services write one portable subset of SQL (``?`` placeholders, ``INSERT OR IGNORE``, integer
flags). The PostgreSQL adapter turns each statement into PostgreSQL at the connection boundary and
turns the SQLite migration scripts into PostgreSQL DDL, so there is one schema definition and one
set of queries. What cannot be translated mechanically is written portably at the call site.
"""

from __future__ import annotations

import re
from collections.abc import Mapping, Sequence
from typing import Any

# Role names are part of the deployment contract (docs/multitenant-operations.md).
APP_ROLE = "aira_app"
PLATFORM_ROLE = "aira_platform"

# Tables that hold no tenant data: every connection may read them, and they carry no policy.
GLOBAL_TABLES = frozenset(
    {
        "cloud_kv",
        "cloud_migrations",
        "plans",
        "plan_versions",
        "feature_flags",
        "announcements",
        "blocked_sources",
        "worker_heartbeats",
    }
)
# Tables only the platform role may touch (operators, platform audit, data-subject requests, raw
# provider events): the tenant role is granted nothing on them.
PLATFORM_ONLY_TABLES = frozenset(
    {
        "operators",
        "platform_audit_logs",
        "data_subject_requests",
        "billing_events",
        "plan_migrations",
    }
)
# Tables whose organization column is not called ``org_id``.
ORG_COLUMN_OVERRIDES = {"airaapi_key_index": "user_id"}

_STRING = re.compile(r"'(?:[^']|'')*'")
_INSERT_OR = re.compile(
    r"\bINSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*\(([^)]*)\)", re.I
)


def _outside_strings(sql: str, transform: Any) -> str:
    """Apply ``transform`` to the parts of ``sql`` that are not single-quoted string literals."""
    parts: list[str] = []
    last = 0
    for match in _STRING.finditer(sql):
        parts.append(transform(sql[last : match.start()]))
        parts.append(match.group(0))
        last = match.end()
    parts.append(transform(sql[last:]))
    return "".join(parts)


def _placeholders(text: str) -> str:
    return text.replace("%", "%%").replace("?", "%s")


def translate(
    sql: str,
    primary_keys: Mapping[str, Sequence[str]] | None = None,
    *,
    named: bool = False,
) -> str:
    """One SQLite-flavoured statement as PostgreSQL, with ``%s`` (or ``%(name)s``) placeholders."""
    statement = sql.strip().rstrip(";")
    if re.match(r"CREATE\s+(TABLE|INDEX)\s+IF\s+NOT\s+EXISTS", statement, re.I):
        # shared code ensures its tables on use; here the migrations own the schema and the app role cannot create
        return "SELECT 1"
    suffix = ""
    match = _INSERT_OR.search(statement)
    if match:
        kind, table, columns = match.groups()
        statement = _INSERT_OR.sub(
            f"INSERT INTO {table} ({columns})", statement, count=1
        )
        names = [c.strip() for c in columns.split(",")]
        if kind.upper() == "IGNORE":
            suffix = " ON CONFLICT DO NOTHING"
        else:
            keys = list((primary_keys or {}).get(table, ()))
            if not keys:
                raise ValueError(
                    f"INSERT OR REPLACE into {table}: no primary key known"
                )
            updates = [n for n in names if n not in keys]
            action = (
                "DO UPDATE SET " + ", ".join(f"{n} = excluded.{n}" for n in updates)
                if updates
                else "DO NOTHING"
            )
            suffix = f" ON CONFLICT ({', '.join(keys)}) {action}"

    def rewrite(text: str) -> str:
        text = re.sub(r"\bLIKE\b", "ILIKE", text)  # SQLite's LIKE ignores ASCII case
        text = re.sub(r"\bMAX\(\s*0\s*,", "GREATEST(0,", text, flags=re.I)
        text = re.sub(
            r"\bPRAGMA\s+defer_foreign_keys\s*=\s*ON\b",
            "SET CONSTRAINTS ALL DEFERRED",
            text,
            flags=re.I,
        )
        if named:
            return re.sub(r"(?<!:):(\w+)", r"%(\1)s", text.replace("%", "%%"))
        return _placeholders(text)

    return _outside_strings(statement + suffix, rewrite)


# ------------------------------------------------------------------------------------------- DDL


def ddl(script_statement: str) -> str:
    """A SQLite DDL statement as PostgreSQL."""
    text = script_statement
    text = re.sub(
        r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        text,
    )
    text = re.sub(r"\bINTEGER\b", "BIGINT", text)
    text = re.sub(r"\bBLOB\b", "BYTEA", text)
    text = re.sub(
        r"(REFERENCES\s+\w+\s*\(\w+\))", r"\1 DEFERRABLE INITIALLY IMMEDIATE", text
    )
    return text


def is_trigger(statement: str) -> bool:
    return statement.lstrip().upper().startswith("CREATE TRIGGER")


