def rls_statements(
    tables: Mapping[str, Sequence[str]], *, force: bool = True
) -> list[str]:
    """Policies and grants for the live schema. ``tables`` maps table name to its column names.

    Every table with an organization column gets ``ENABLE`` and ``FORCE ROW LEVEL SECURITY`` and one
    policy: a row is visible and writable only when its organization equals ``app.org_id``, which the
    adapter sets from the tenant scope of the transaction. With no scope the setting is NULL, the
    comparison is NULL and no row matches: a missing filter returns nothing instead of leaking.
    The platform role carries ``BYPASSRLS`` (set when the role is created).
    """
    statements: list[str] = []
    for name, columns in sorted(tables.items()):
        if name in GLOBAL_TABLES:
            continue
        column = ORG_COLUMN_OVERRIDES.get(name, "org_id")
        statements.append(f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY")
        statements.append(
            f"ALTER TABLE {name} {'FORCE' if force else 'NO FORCE'} ROW LEVEL SECURITY"
        )
        statements.append(f"DROP POLICY IF EXISTS tenant_isolation ON {name}")
        if name in PLATFORM_ONLY_TABLES or column not in columns:
            continue
        statements.append(
            f"CREATE POLICY tenant_isolation ON {name} FOR ALL "
            f"USING ({column} = current_setting('app.org_id', true)) "
            f"WITH CHECK ({column} = current_setting('app.org_id', true))"
        )
    return statements


def tenant_columns(table_columns: Mapping[str, Sequence[str]]) -> dict[str, list[str]]:
    """The tables that belong under a policy: those with an organization column."""
    out: dict[str, list[str]] = {}
    for name, columns in table_columns.items():
        column = ORG_COLUMN_OVERRIDES.get(name, "org_id")
        if name in GLOBAL_TABLES or column in columns or name in PLATFORM_ONLY_TABLES:
            out[name] = list(columns)
    return out
